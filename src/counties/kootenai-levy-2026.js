// "2490000" | "249-0000" | 2490000 -> "249-0000"; anything else -> null.
export function kootenaiTagKey(value) {
  const s = String(value ?? '').trim();
  let m = /^(\d{3})-(\d{4})$/.exec(s);
  if (m) return `${m[1]}-${m[2]}`;
  m = /^(\d{7})$/.exec(s);
  return m ? `${s.slice(0, 3)}-${s.slice(3)}` : null;
}

// Levy rate (fraction of net taxable value) for a GIS TAG, or null when the TAG is not in the table.
export function kootenaiLevyRate(tag) {
  const key = kootenaiTagKey(tag);
  return key && Object.hasOwn(KOOTENAI_LEVY_RATES_2026, key) ? KOOTENAI_LEVY_RATES_2026[key] : null;
}
